"""
Пинг с сервера панели: второе мнение о недоступной точке.

Зачем
-----

Доступность у панели означает «отвечает API»: она стучится на 8728,
и это правильный вопрос, потому что через API она и работает. Но у
этого ответа есть неприятная двусмысленность. «Оффлайн» одинаково
выглядит и когда площадку обесточили, и когда роутер жив, а до его
API не достучаться: канал захлёбывается, туннель моргает, на самом
роутере закрылся сервис.

Разница огромная. В первом случае надо ехать или звонить, во втором
чинить канал, и WinBox при этом спокойно работает, потому что его
сессия уже установлена. Именно так и выглядела жалоба: «точка висит
не в сети, хотя по факту доступна».

Пинг отвечает на второй вопрос: жив ли хост вообще. Он ничего не
меняет в статусе - тот по-прежнему про API, - но добавляет к нему
объяснение.

Как сделано
-----------

Через системный `ping`, а не через сырой сокет: сырой ICMP требует
прав администратора, а панель обязана работать обычным пользователем.
Если `ping` в системе нет (случается в тощих контейнерах), проверка
молча выключается: она вспомогательная и падать из-за неё нельзя.
"""

from __future__ import annotations

import logging
import shutil
import subprocess

log = logging.getLogger("tikpilot.icmp")

#: Сколько ждём ответа. Одна секунда: это не измерение задержки,
#: а вопрос «ты вообще там есть». Задержку меряет сам роутер.
TIMEOUT = 1

_binary: str | None | bool = False   # False значит «ещё не искали»


def available() -> bool:
    """Есть ли в системе `ping`. Результат запоминается."""
    global _binary
    if _binary is False:
        _binary = shutil.which("ping")
        if _binary is None:
            log.info("Команда ping не найдена, проверка ICMP выключена")
    return bool(_binary)


def alive(host: str, timeout: int = TIMEOUT) -> bool | None:
    """
    Отвечает ли хост на ICMP.

    Возвращает None, когда сказать нечего: пинга в системе нет, адрес
    пустой или сама команда не отработала. None это не «не отвечает»,
    и путать их нельзя: молчание проверки не повод объявлять точку
    живой или мёртвой.
    """
    host = str(host or "").strip()
    if not host or not available():
        return None

    try:
        answer = subprocess.run(
            [str(_binary), "-n", "-c", "1", "-w", str(max(1, timeout)), host],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=max(2, timeout + 2),
            check=False,
        )
    except (OSError, subprocess.SubprocessError) as exc:  # noqa: BLE001
        log.debug("Пинг %s не выполнился: %s", host, exc)
        return None

    return answer.returncode == 0
